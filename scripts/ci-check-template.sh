#!/usr/bin/env bash
# Checks the deployment template against the working-tree Worker build.
#
# The template is installed standalone by Workers Builds, so it is not part
# of the pnpm workspace. This type-checks it, runs its unit tests, and
# validates wrangler.jsonc against the local Worker build, not the last npm
# release: a plain `pnpm install` would resolve cf-nix-cache from the
# registry, while `check:ci` requires the working tree's release manifest.
# Packing the just-built Worker and installing the tarball via `file:` keeps
# the template pinned to the working tree.
#
# The monorepo tracks no lockfile for the template: the lock is generated by
# publish-release.yml and lives only in the public template repository. This
# installs without --frozen-lockfile so a missing lockfile is generated
# ephemerally, and only the cf-nix-cache entry floats to the working-tree
# tarball via `pnpm add`. The wrangler dry-run also runs here on the
# working-tree build: like the template's own validate workflow, it compiles
# and validates locally and needs no Cloudflare credentials, so forks without
# secrets still pass.
set -euo pipefail

# This script is for ephemeral CI runners: the install/add below mutates
# package.json, the lockfile, and node_modules, of which only the first two
# are restored. node_modules is gitignored and discarded with the runner, and
# the tarball linked by `pnpm add file:` lives in a temp dir removed on EXIT,
# so a local run outside CI must reinstall afterwards. The trap restores the
# manifests only for local `act` reruns.
tmpdir=$(mktemp -d)
backup_pkg=$(mktemp)
backup_lock=$(mktemp)
cp cf-nix-cache-template/package.json "$backup_pkg"
has_lock=0
if [ -f cf-nix-cache-template/pnpm-lock.yaml ]; then
  cp cf-nix-cache-template/pnpm-lock.yaml "$backup_lock"
  has_lock=1
fi
cleanup() {
  if [ -f "$backup_pkg" ]; then
    mv "$backup_pkg" cf-nix-cache-template/package.json
  fi
  if [ "$has_lock" = 1 ]; then
    if [ -f "$backup_lock" ]; then
      mv "$backup_lock" cf-nix-cache-template/pnpm-lock.yaml
    else
      rm -f cf-nix-cache-template/pnpm-lock.yaml
    fi
  else
    rm -f cf-nix-cache-template/pnpm-lock.yaml "$backup_lock"
  fi
  rm -rf "$tmpdir"
}
trap cleanup EXIT
nix develop --command npm pack ./packages/worker --pack-destination "$tmpdir"
shopt -s nullglob
tarballs=("$tmpdir"/cf-nix-cache-*.tgz)
if (( ${#tarballs[@]} == 0 )); then
  echo "ci-check-template: no cf-nix-cache tarball found in $tmpdir" >&2
  exit 1
fi
tarball="${tarballs[0]}"
test -f "$tarball"
nix develop --command pnpm --dir cf-nix-cache-template install --no-frozen-lockfile
nix develop --command pnpm --dir cf-nix-cache-template add "file:$tarball"
nix develop --command pnpm --dir cf-nix-cache-template run check:ci
# Dry-run the working-tree build. This needs no Cloudflare credentials (it
# compiles and validates locally), so it runs in monorepo CI as well as in
# the template's own validate workflow.
nix develop --command pnpm --dir cf-nix-cache-template exec wrangler deploy --dry-run
